from typing import Protocol, TypeVar

from ddnevnik.models import Course, CourseCriterion, Criterion, Enrollment, Mark, Student

from .results import CourseCriterionResult

EntityT = TypeVar("EntityT")
EntityKey = int | tuple[int, ...]


class Repository(Protocol[EntityT]):
    def get(self, key: EntityKey) -> EntityT: ...

    def list(self, *, limit: int = 100, offset: int = 0) -> list[EntityT]: ...

    def save(self, entity: EntityT) -> EntityT: ...

    def delete(self, entity: EntityT) -> None: ...


class StudentRepository(Repository[Student], Protocol):
    def get_course(self, course_id: int) -> Course: ...

    def find_enrollment(self, student_id: int, course_id: int) -> Enrollment | None: ...

    def add_enrollment(self, student_id: int, course_id: int) -> Enrollment: ...

    def get_courses(
        self, student_id: int, *, limit: int | None = 100, offset: int = 0
    ) -> list[Course]: ...

    def get_rubrics(self, student_id: int) -> list[CourseCriterionResult]: ...

    def get_marks(self, student_id: int) -> list[Mark]: ...


class CourseRepository(Repository[Course], Protocol):
    def get_student(self, student_id: int) -> Student: ...

    def get_criterion(self, criterion_id: int) -> Criterion: ...

    def get_enrollment(self, student_id: int, course_id: int) -> Enrollment: ...

    def find_enrollment(self, student_id: int, course_id: int) -> Enrollment | None: ...

    def add_enrollment(self, student_id: int, course_id: int) -> Enrollment: ...

    def find_criterion(self, course_id: int, criterion_id: int) -> CourseCriterion | None: ...

    def add_criterion(
        self, course_id: int, criterion_id: int, weight: float
    ) -> CourseCriterion: ...

    def get_students(
        self, course_id: int, *, limit: int | None = 100, offset: int = 0
    ) -> list[Student]: ...

    def get_rubric(self, course_id: int) -> list[CourseCriterionResult]: ...

    def get_marks(self, course_id: int, *, student_id: int | None = None) -> list[Mark]: ...


class CriteriaRepository(Repository[Criterion], Protocol):
    def get_highest_mark(self, criterion_id: int) -> int | None: ...


class MarkRepository(Repository[Mark], Protocol):
    def get_student(self, student_id: int) -> Student: ...

    def get_course(self, course_id: int) -> Course: ...

    def get_criterion(self, criterion_id: int) -> Criterion: ...

    def get_enrollment(self, student_id: int, course_id: int) -> Enrollment: ...

    def find(self, student_id: int, course_id: int, criterion_id: int) -> Mark | None: ...

    def find_enrollment(self, student_id: int, course_id: int) -> Enrollment | None: ...

    def find_course_criterion(
        self, course_id: int, criterion_id: int
    ) -> CourseCriterion | None: ...

    def get_student_marks(self, student_id: int, course_id: int) -> list[Mark]: ...
